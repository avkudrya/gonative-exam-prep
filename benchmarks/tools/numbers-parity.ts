/*
 * Parity fixture for the PHP port of checkNumbers (MultiAdmin app/Services/Exam/Assessment/ChartNumbers.php): every
 * response of exam-t1a-v1 and every code fact of the Task 1 library, with the mentions the TS check finds.
 *
 *   node --import tsx benchmarks/tools/numbers-parity.ts <out.json>
 */

import {writeFileSync} from 'node:fs';
import {chartFacts, checkNumbers, type ChartSpec} from '../../packages/exam-domain/src/index.js';
import {buildT1Items, readT1Inputs} from './build-t1.js';

const {tasks, bases, essays} = readT1Inputs();
const cases: Array<{id: string; text: string; spec: ChartSpec; mentions: ReturnType<typeof checkNumbers>}> = [];
for (const item of buildT1Items(tasks, bases, essays)) {
  if (item.source.case === 'essay_instead' || item.source.case === 'data_dump') continue;
  cases.push({id: item.id, text: item.text, spec: item.stimulus, mentions: checkNumbers(item.text, item.stimulus)});
}
for (const t of tasks) {
  const text = t.stimulus.charts.flatMap(c => chartFacts(c).map(f => f.text)).join(' ');
  cases.push({id: `facts-${t.ref.split(':')[1]}`, text, spec: t.stimulus, mentions: checkNumbers(text, t.stimulus)});
}
const out = process.argv[2];
if (!out) throw new Error('usage: numbers-parity.ts <out.json>');
writeFileSync(out, JSON.stringify({about: 'Generated by gonative-exam-prep benchmarks/tools/numbers-parity.ts; do not edit.', cases}) + '\n');
console.log(`${cases.length} cases, ${cases.reduce((n, c) => n + c.mentions.length, 0)} mentions`);
